const glyphs: Record<string, boolean[][]> = {}
for (const [ch, rows] of Object.entries(G)) {
  const r = rows.split(' ')
  const w = r[0].length
  // store column-major: glyph[col][row]
  glyphs[ch] = Array.from({ length: w }, (_, c) => r.map((row) => row[c] === '#'))
}

export type Column = { bits: boolean[]; char: number }

/** Convert a string into LED columns (7 bits each) with 1-column spacing. */
export function textToColumns(text: string): Column[] {
  const out: Column[] = []
  let charIndex = 0
  for (const raw of text.toUpperCase()) {
    const g = glyphs[raw] ?? glyphs['?']
    for (const bits of g) out.push({ bits, char: charIndex })
    out.push({ bits: [false, false, false, false, false, false, false], char: charIndex })
    if (raw !== ' ') charIndex++
  }
  return out
}

